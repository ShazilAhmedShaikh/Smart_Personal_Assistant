def generate_scraper(url: str, framework: str = "playwright") -> Dict[str, Any]:
    """Generates an optimized web scraper template for a given target URL."""
    f = framework.lower().strip()
    template = SCRAPING_TEMPLATES.get(f, SCRAPING_TEMPLATES["playwright"])
    clean_url = url.strip()
    if not clean_url.startswith("http"):
        clean_url = "https://" + clean_url

    code = template.format(url=clean_url)
    
    # Save script to projects directory
    out_dir = Path(DEFAULT_PROJECTS_DIR) / "scrapers"
    out_dir.mkdir(parents=True, exist_ok=True)
    filename = f"scraper_{f}_{int(time.time())}.py"
    target_path = out_dir / filename
    target_path.write_text(code, encoding="utf-8")

    return {
        "success": True,
        "framework": f,
        "url": clean_url,
        "saved_path": str(target_path),
        "code_snippet": code[:500] + "\n...",
        "message": f"Production-grade {f.title()} scraper template generated at `{target_path}`."
    }
